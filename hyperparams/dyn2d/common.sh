#!/usr/bin/env bash
# Shared Dyn2D defaults. Training reuses the Dyn3D direct-vector MLP objective.
HP_POSITIVE_MODE="mean"
HP_NUM_FOLDS=2
HP_VAL_FRACTION=0.5
HP_MLP_HIDDEN=256
HP_EPOCHS=2000
HP_BATCH_SIZE=256
HP_LEARNING_RATE=0.001
HP_SEED=42
HP_DEVICE="cuda"
HP_EXTRACT_BATCH_SIZE=1
HP_DTYPE="float16"
HP_EVAL_SPLIT="test"
HP_STRENGTH=1.0
HP_SLERP_T=0.5
HP_EVAL_PRESET="qa"
HP_JUDGE_PRESET="null"
HP_MAX_NEW_TOKENS=50

apply_dyn2d_common() {
  POSITIVE_MODE="${POSITIVE_MODE:-$HP_POSITIVE_MODE}"
  NUM_FOLDS="${NUM_FOLDS:-$HP_NUM_FOLDS}"
  VAL_FRACTION="${VAL_FRACTION:-$HP_VAL_FRACTION}"
  MLP_HIDDEN="${MLP_HIDDEN:-$HP_MLP_HIDDEN}"
  EPOCHS="${EPOCHS:-$HP_EPOCHS}"
  BATCH_SIZE="${BATCH_SIZE:-$HP_BATCH_SIZE}"
  LEARNING_RATE="${LEARNING_RATE:-$HP_LEARNING_RATE}"
  SEED="${SEED:-$HP_SEED}"
  DEVICE="${DEVICE:-$HP_DEVICE}"
  EXTRACT_BATCH_SIZE="${EXTRACT_BATCH_SIZE:-$HP_EXTRACT_BATCH_SIZE}"
  DTYPE="${DTYPE:-$HP_DTYPE}"
  EVAL_SPLIT="${EVAL_SPLIT:-$HP_EVAL_SPLIT}"
  STRENGTH="${STRENGTH:-$HP_STRENGTH}"
  SLERP_T="${SLERP_T:-$HP_SLERP_T}"
  EVAL_PRESET="${EVAL_PRESET:-$HP_EVAL_PRESET}"
  JUDGE_PRESET="${JUDGE_PRESET:-$HP_JUDGE_PRESET}"
  MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-$HP_MAX_NEW_TOKENS}"
}
